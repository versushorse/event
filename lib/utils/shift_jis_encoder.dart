  /// 日本語文字列をShift_JIS（CP932）のパーセントエンコード形式（%XX%YY）に変換する
  static String encodeUriComponent(String text) {
    final table = _cache ??= _buildTable();
    final sb = StringBuffer();
    for (final r in text.runes) {
      if (_isUnreserved(r)) {
        sb.writeCharCode(r);
      } else if (r == 0x20 || r == 0x3000) {
        sb.write('%20');
      } else if (r > 0x20 && r <= 0x7E) {
        sb.write('%');
        sb.write(r.toRadixString(16).toUpperCase().padLeft(2, '0'));
      } else {
        final sjis = table[r];
        if (sjis == null) {
          continue;
        }
        if (sjis <= 0xFF) {
          sb.write('%');
          sb.write(sjis.toRadixString(16).toUpperCase().padLeft(2, '0'));
        } else {
          final b1 = (sjis >> 8) & 0xFF;
          final b2 = sjis & 0xFF;
          sb.write('%');
          sb.write(b1.toRadixString(16).toUpperCase().padLeft(2, '0'));
          sb.write('%');
          sb.write(b2.toRadixString(16).toUpperCase().padLeft(2, '0'));
        }
      }
    }
    return sb.toString();
  }

  static bool _isUnreserved(int r) {
    return (r >= 0x30 && r <= 0x39) || // 0-9
        (r >= 0x41 && r <= 0x5A) || // A-Z
        (r >= 0x61 && r <= 0x7A) || // a-z
        r == 0x2D || // -
        r == 0x5F || // _
        r == 0x2E || // .
        r == 0x7E; // ~
  }

  static Map<int, int> _buildTable() {
    final bytes = base64Decode(_tableBase64);
